package com.fundcompass.matching.domain;

/**
 * 판정하지 못한 이유. <b>사용자에게 요구할 행동이 서로 다르므로 구분한다.</b>
 *
 * <p>전부 "확인필요"로 뭉치면 공고가 애초에 따지지 않는 조건까지 숙제로 떠넘긴다.
 * 실측에서 조건 슬롯의 56.6%가 {@link #NOT_STATED}였다 — 이걸 사용자 과제로 표시하면
 * 화면이 할 일 목록으로 뒤덮인다.
 */
public enum UnknownReason {
    /**
     * 공고문에 이 조건이 없다. 가장 흔하다 — 조건 슬롯 8,682개 중 4,902개(56%).
     *
     * <p><b>제약 없음으로 취급한다</b>(2026-08-18 결정). 따라서 적격 판정을 막지 않는다.
     * 사용자가 할 일도 없다 — 표시하되 행동을 요구하지 않는다.
     *
     * <p>이 결정 전에는 모든 미상이 적격을 막았고, 모든 공고에 {@code NOT_STATED}가 최소 하나
     * 있으므로 {@link EligibilityVerdict#ELIGIBLE}이 <b>1,447건 전부에서 한 번도 발생하지 않았다</b>.
     * 기획서 3분류의 한 분기가 죽은 코드였다.
     *
     * <p>⚠️ <b>감수하는 위험:</b> 공고문에 조건이 있는데 F2가 놓친 경우를 "제약 없음"으로 본다.
     * F2의 판정률이 43.4%라 놓쳤을 가능성이 작지 않다. {@code MATCHED 97.8%}가 보장하는 것은
     * <b>뽑은 것이 정확하다</b>는 것뿐이고, 안 뽑은 것에 대해서는 아무 정보가 없다.
     * F7 검수와 F5 설명에서 "공고문 원문을 확인하세요"를 함께 노출해 완화한다.
     */
    NOT_STATED,

    /**
     * 조건은 뽑혔으나 근거가 원문과 어긋나 신뢰할 수 없다
     * ({@code unverified_fields}: ALTERED 27건 + MISSING 9건).
     * 사용자에게는 {@link #NOT_STATED}와 같게 보이지만 내부적으로는 F7 검수 대상이다.
     */
    EVIDENCE_UNTRUSTED,

    /**
     * 공고는 조건을 걸었는데 프로필에 해당 값이 없다.
     * <b>유일하게 사용자 행동으로 해소되는 경우다</b> — "매출을 입력하면 정확해집니다".
     */
    PROFILE_MISSING,

    /**
     * 공고의 값을 우리가 해석하지 못했다 (예: 어느 시의 구인지 모호한 {@code 서구}).
     * 사용자 잘못이 아니므로 행동을 요구하지 않고, 정규화 개선 대상으로 남긴다.
     */
    NOT_NORMALIZABLE,

    /**
     * 프로필 값이 구간이고 그 구간이 조건 경계를 걸친다
     * (예: 매출 {@code 1억~3억} 프로필 vs {@code 2억 이하} 조건).
     * 개인정보 최소 수집(F13)을 위해 매출을 구간으로 받은 것의 대가다.
     */
    BAND_STRADDLES_BOUNDARY
}
